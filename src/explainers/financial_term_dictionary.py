def get_term_explanation(term_keyword: str) -> str:
    """
    금융 용어의 설명을 조회합니다.
    
    Args:
        term_keyword: 용어 키워드 (예: "ROE", "부채비율")
    
    Returns:
        용어 설명 문자열, 없으면 빈 문자열
    """
    return FINANCIAL_TERM_DICTIONARY.get(term_keyword, "")


def get_all_terms() -> Dict[str, str]:
    """
    모든 금융 용어 사전을 반환합니다.
    
    Returns:
        전체 용어 사전 딕셔너리
    """
    return FINANCIAL_TERM_DICTIONARY.copy()


def format_term_glossary_section(selected_terms: list[str] | None = None) -> str:
    """
    용어 사전을 텍스트 형식으로 포맷팅합니다.
    
    Args:
        selected_terms: 선택적으로 포함할 용어 리스트 (None이면 주요 15개 지표만)
    
    Returns:
        포맷팅된 용어 사전 문자열
    """
    if selected_terms is None:
        # 기본: 15개 핵심 지표만 포함
        selected_terms = [
            "매출액 성장률", "영업이익 성장률", "EPS", "FCF",
            "영업이익률", "ROE", "ROA", "ROIC",
            "부채비율", "유동비율", "이자보상배율",
            "PER", "PBR", "EV/EBITDA"
        ]
    
    lines = ["[금융 용어 해설]"]
    lines.append("=" * 80)
    
    for term in selected_terms:
        explanation = get_term_explanation(term)
        if explanation:
            lines.append(f"\n■ {term}")
            lines.append(f"  {explanation}")
    
    lines.append("=" * 80)
    return "\n".join(lines)


